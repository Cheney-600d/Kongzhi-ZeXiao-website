function openSchoolModal(schoolName, subject) {
    let dataSource = subject === '0809' ? SCHOOL_DATA_0809 : SCHOOL_DATA;
    // 名称映射：处理HTML中名称与数据键不一致的情况
    const nameMap = {
        '解放军理工大学': '陆军工程大学',
        '海军航空工程学院': '海军航空大学'
    };
    let lookupName = nameMap[schoolName] || schoolName;
    let data = dataSource[lookupName];
    if (!data) {
        // 尝试去掉前缀匹配军事院校
        let shortName = schoolName.replace(/^中国人民解放军/, '').replace(/^战略支援部队/, '');
        let key = Object.keys(dataSource).find(k => {
            let kShort = k.replace(/（\d+）/g, '');
            return kShort.includes(shortName) || shortName.includes(kShort);
        });
        if (key) data = dataSource[key];
    }
    if (!data) {
        alert('暂无 "' + schoolName + '" 的详细数据');
        return;
    }
    
    let html = '<div class="modal-overlay active" id="schoolModalOverlay" onclick="if(event.target===this)closeSchoolModal()">';
    html += '<div class="modal-box">';
    html += '<span class="modal-close" onclick="closeSchoolModal()">&times;</span>';
    html += '<div class="modal-title">' + schoolName + ' — ' + (subject === '0809' ? '0809电子科学与技术' : '0810信息与通信工程') + '</div>';
    
    html += '<div class="modal-section">';
    html += '<h4>学校特色</h4>';
    html += '<p>' + data.feature + '</p>';
    html += '</div>';
    
    if (data.research) {
        html += '<div class="modal-section">';
        html += '<h4>硕士研究方向</h4>';
        let research = data.research;
        if (research.includes('|')) {
            let rows = research.split('\n').filter(r => r.trim().startsWith('|'));
            if (rows.length > 0) {
                html += '<table>';
                rows.forEach((row, idx) => {
                    if (row.replace(/[-|]/g, '').trim() === '') return;
                    let cells = row.split('|').filter(c => c.trim() !== '');
                    let tag = idx === 0 ? 'th' : 'td';
                    html += '<tr>' + cells.map(c => '<' + tag + '>' + c.trim() + '</' + tag + '>').join('') + '</tr>';
                });
                html += '</table>';
            } else {
                html += '<p>' + research.replace(/\n/g, '<br>') + '</p>';
            }
        } else {
            html += '<p>' + research.replace(/\n/g, '<br>') + '</p>';
        }
        html += '</div>';
    }
    
    if (data.employment) {
        html += '<div class="modal-section">';
        html += '<h4>对口就业行业/公司</h4>';
        let emp = data.employment.replace(/\n/g, '<br>');
        emp = emp.replace(/- \*\*([^*]+)\*\*/g, '<strong>$1</strong>');
        html += '<p>' + emp + '</p>';
        html += '</div>';
    }
    
    html += '</div></div>';
    
    const existing = document.getElementById('schoolModalOverlay');
    if (existing) existing.remove();
    
    document.body.insertAdjacentHTML('beforeend', html);
    document.body.style.overflow = 'hidden';
}

function closeSchoolModal() {
    const modal = document.getElementById('schoolModalOverlay');
    if (modal) {
        modal.remove();
        document.body.style.overflow = '';
    }
}

document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape') closeSchoolModal();
});

